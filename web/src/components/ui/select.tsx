        "relative flex w-full cursor-default items-center gap-1.5 min-h-8 py-1.5 pr-8 pl-3 text-sm select-none focus:bg-accent focus:shadow-[inset_2px_0_0_var(--rubric)] focus:text-accent-foreground focus-visible:outline-none not-data-[variant=destructive]:focus:**:text-accent-foreground data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 *:[span]:last:flex *:[span]:last:items-center *:[span]:last:gap-2",
        className
