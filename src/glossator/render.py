GENERATED = "Generated by glossator from the records. Edit record.json, then run: glossator build"


URL_RE = re.compile(r"https?://[^\s<>()\"']+[^\s<>()\"'.,;:]")


def val(x) -> list:
    """A record value as inline parts: sentinels muted, TODOs flagged, URLs linked."""
    if isinstance(x, bool):
        return ["yes" if x else "no"]
    if not isinstance(x, str):
        return [str(x)]
    s = x.strip()
    if s in SENTINELS or s == NO_FIGURE:
        return [("muted", s)]
    if s.upper().startswith("TODO"):
        return [("todo", s)]
    parts, pos = [], 0
    for m in URL_RE.finditer(s):
        parts += [s[pos : m.start()], ("a", m.group(0), m.group(0))]
        pos = m.end()
    parts.append(s[pos:])
    return [p for p in parts if p]


def vals(values, vocab) -> list:
    """Values of a vocabulary (records.Vocabulary) by their labels."""
    out = []
    for i, v in enumerate(values):
        out += ([" · "] if i else []) + (val(v) if is_sentinel(v) or str(v).startswith("TODO") else [vlabel(vocab, v)])
    return out or [("muted", "none")]


def vword(vocab, value) -> list:
    """A value of a vocabulary (records.Vocabulary) by its label."""
    return val(value) if is_sentinel(value) or str(value).startswith("TODO") else [vlabel(vocab, value)]


def as_text(parts: list) -> str:
    """Inline parts as plain text."""
    return "".join(p if isinstance(p, str) else p[-1] for p in parts)


def related_link(r: dict) -> tuple:
    link = r["link"]
    return ("a", f"https://doi.org/{link}" if DOI_RE.match(link) else link, r["cite"])


def joined(items: list[list], sep: str = ", ") -> list:
    out = []
    for i, item in enumerate(items):
        out += ([sep] if i else []) + item
    return out


def short_authors(authors: list[str]) -> str:
    if len(authors) <= 8:
        return ", ".join(authors)
    return ", ".join(authors[:6]) + f", … , {authors[-1]} ({len(authors)} authors)"


def page_head(rec: dict) -> tuple[list, list]:
    """The bibliographic line and the file buttons of an article's page."""
    b = rec["bib"]
    meta = [("em", b["venue"])]
    vol = " ".join(
        x for x in (b["volume"], f"({b['issue']})" if not is_sentinel(b["issue"]) else "") if x and not is_sentinel(x)
    )
    if vol:
        meta += [f" {vol}"]
    if not is_sentinel(b["pages"]):
        meta += [f": {b['pages']}"]
    meta += [f" · {b['date']} · ", ("a", f"https://doi.org/{b['doi']}", f"doi:{b['doi']}")]
    if not is_sentinel(b["pmid"]):
        meta += [" · ", ("a", f"https://pubmed.ncbi.nlm.nih.gov/{b['pmid']}/", f"PMID {b['pmid']}")]
    if not is_sentinel(b["pmcid"]):
        meta += [" · ", ("a", f"https://pmc.ncbi.nlm.nih.gov/articles/{b['pmcid']}/", b["pmcid"])]

    files = [
        (
            "paper.pdf",
            "PDF · "
            + (
                vlabel(VOCAB["paper_version"], rec["paper"]["version"])
                if rec["paper"]["version"] in VOCAB["paper_version"]
                else "to fetch"
            ),
            True,
        )
    ]
    files += [(f["file"], f["label"], False) for f in rec["supplementary"]["files"]]
    files += [("record.json", "record.json", False)]
    return meta, files


def open_points_section(rec: dict) -> tuple:
    return (
        "open-points",
        "Open points",
        [("bullets", [val(x) for x in rec["open_points"]])] if rec["open_points"] else [("p", [("muted", "none")])],
    )


def provenance_section(rec: dict) -> tuple:
    pp, sp, cur = rec["paper"], rec["supplementary"], rec["curation"]
    copy = (
        vword(VOCAB["paper_version"], pp["version"])
        + [
            " from ",
            *val(pp["host"]),
            " (licence: ",
            *val(pp["license"]),
            f"), {pp['pages']} pages, retrieved ",
            *val(pp["retrieved"]),
            " · ",
            ("a", pp["source_url"], "source"),
        ]
        if pp["source_url"].startswith("http")
        else val(pp["source_url"])
    )
    supp = vword(VOCAB["supplementary_status"], sp["status"]) + [". ", *val(sp["note"])]
    fields = [
        ("Paper", copy),
        ("Note on the copy", val(pp["note"])),
        ("SHA-256", [pp["sha256"][:16] + "…" if len(pp["sha256"]) == 64 else pp["sha256"]]),
        ("Supplementary", supp),
    ]
    if sp["files"]:
        fields.append(
            (
                "Supplementary files",
                joined([[("a", f["file"], f["label"]), f" ({f['file'].split('/')[-1]})"] for f in sp["files"]]),
            )
        )
    fields += [("Read", val(cur["read"])), ("Curated", val(cur["date"]))]
    blocks = [("fields", fields)]
    if cur["checks"]:
        blocks += [
            ("h3", "Claims checked on request"),
            ("bullets", [[*val(c["claim"]), " → ", ("b", c["verdict"])] for c in cur["checks"]]),
        ]
    return ("provenance", "Sources and provenance", blocks)


def page_view(rec: dict, glance: list, sections: list) -> dict:
    b, key = rec["bib"], rec["key"]
    meta, files = page_head(rec)
    kicker = [b["cite"], " · ", *val(b["place"])]
    return {
        "key": key,
        "title": b["title"],
        "kicker": kicker,
        "authors": short_authors(b["authors"]),
        "meta": meta,
        "lab": val(b["lab"]),
        "files": files,
        "lead": val(rec["overview"]["one_line"]),
        "draft": rec["status"] != "complete",
        "glance": glance,
        "sections": sections,
        "footer": [f"Curated on {rec['curation']['date']} by the curator agent. {GENERATED}"],
    }


def article_view(rec: dict, coll: dict) -> dict:
    """The article's view: the base's overview first, its profile's tiles and sections, the base's open points and
    provenance last."""
    glance, sections = coll.biblio.plugin.view(rec, coll)
    overview = ("overview", "Overview", [("p", val(p)) for p in rec["overview"]["abstract"]])
    return page_view(rec, glance, [overview, *sections, open_points_section(rec), provenance_section(rec)])


def headline_lines(results: list) -> list:
    """The headline results as the lines of a tile: value, what is measured, what it holds for."""
    return [[("b", m["value"]), " ", m["name"], ("muted", f" ({m['condition']})")] for m in results if m["headline"]]


def results_blocks(results: list) -> list:
    if not results:
        return [("p", [("muted", "none")])]
    return [
        (
            "table",
            ["★", "Metric", "Value", "Condition", "Chance or baseline", "Source"],
            [
                [
                    ["★"] if m["headline"] else [],
                    val(m["name"]),
                    [("b", m["value"])],
                    val(m["condition"]),
                    val(m["baseline"]),
                    val(m["source"]),
                ]
                for m in results
            ],
        ),
        ("source", ["★ headline metric. Values as printed in the paper; ≈ read from a figure."]),
    ]


def figure_block(fig: dict, alt: str) -> tuple:
    """A figure of the record (an entry of `figures`) as a block."""
    return ("figure", fig["file"], alt, [*val(fig["caption"]), " (", *val(fig["from"]), ")"])


def quotes_blocks(quotes: list, coll: dict) -> list:
    """The paper's sentences as quotes ('none' when there is none)."""
    return [("quote", val(qt["text"]), quote_where(qt, coll)) for qt in quotes if not is_sentinel(qt["text"])] or [
        ("p", [("muted", "none")])
    ]


def quote_where(qt: dict, coll: dict) -> list:
    where = val(qt["where"])
    src = qt["in"]
    if src == THIS_PAPER:
        return where
    k = coll.doi2key.get(src.lower())
    link = ("art", k, coll.recs[k]["bib"]["cite"]) if k else ("a", f"https://doi.org/{src}", f"doi:{src}")
    return [*where, ", in ", link]


def related_item(r: dict, coll: dict, about: str = "") -> list:
    k = coll.doi2key.get(r["link"].lower())
    item = [related_link(r), ": ", ("em", r["title"]), ". ", *val(r["why"])] + ([f" ({about})"] if about else [])
    return item + ([" · in this collection: ", ("art", k, k)] if k else [])


# The bibliographies seen from the page (build/index.html): ../library unless GLOSSATOR_LIBRARY moves them.
LIBRARY_HREF = Path(os.path.relpath(LIBRARY, BUILD)).as_posix()


class Links:
    """Where another article and an article's own files are, seen from what is being written: the page of every
    bibliography (build/index.html: an article is `#<bibliography>/<key>`, its files under
    `../library/<bibliography>/articles/<key>/`), or
    an article's Markdown summary (its files relative to its folder)."""

    def __init__(self, fmt: str, biblio: Bibliography, key: str = ""):
        self.fmt, self.bib, self.key = fmt, biblio.name, key

    def art(self, key: str) -> str:
        return f"#{self.bib}/{key}"

    def file(self, href: str) -> str:
        if self.fmt == "md" or href.startswith(("http:", "https:", "#")):
            return href
        return f"{LIBRARY_HREF}/{self.bib}/articles/{self.key}/{href}"  # the page is in build/


def md_mark(text: str, mark: str) -> str:
    """*text* with the spaces outside the marks, or Markdown does not render it."""
    core = text.strip()
    if not core:
        return text
    return f"{text[: len(text) - len(text.lstrip())]}{mark}{core}{mark}{text[len(text.rstrip()) :]}"


def md_inl(parts: list, links: Links) -> str:
    out = []
    for p in parts:
        if isinstance(p, str):
            out.append(p)
        elif p[0] == "a":
            out.append(f"[{p[2]}]({p[1].replace(' ', '%20')})")
        elif p[0] == "art":
            out.append(f"[{p[2]}]({links.art(p[1])})")
        elif p[0] in ("em", "muted"):
            out.append(md_mark(p[1], "*"))
        elif p[0] in ("b", "todo"):
            out.append(md_mark(p[1], "**"))
        elif p[0] == "badge":
            out.append(f" `{p[1]}`")
        elif p[0] == "sub" and p[1]:
            out.append(f" — {p[1]}")
    return re.sub(r"\s*\n\s*", " ", "".join(out))


def md_cell(parts: list, links: Links) -> str:
    return md_inl(parts, links).replace("|", "\\|") or " "


def md_blocks(blocks: list, links: Links) -> str:
    out = []
    for blk in blocks:
        kind = blk[0]
        if kind == "p":
            out.append(md_inl(blk[1], links))
        elif kind == "h3":
            out.append(f"### {blk[1]}")
        elif kind == "fields":
            out.append("\n".join(f"- **{label}:** {md_inl(v, links)}" for label, v in blk[1]))
        elif kind == "bullets":
            out.append("\n".join(f"- {md_inl(v, links)}" for v in blk[1]))
        elif kind == "table":
            head, rows = blk[1], blk[2]
            lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
            lines += ["| " + " | ".join(md_cell(c, links) for c in row) + " |" for row in rows]
            out.append("\n".join(lines))
        elif kind == "quote":
            out.append(f"> “{md_inl(blk[1], links)}”  \n> — {md_inl(blk[2], links)}")
        elif kind == "figure":
            out.append(f"![{blk[2]}]({blk[1]})  \n*{md_inl(blk[3], links)}*")
        elif kind == "source":
            out.append(f"*{md_inl(blk[1], links)}*")
    return "\n\n".join(out)


def h_inl(parts: list, links: Links) -> str:
    e = html.escape
    out = []
    for p in parts:
        if isinstance(p, str):
            out.append(e(p))
        elif p[0] == "a":
            ext = ' target="_blank" rel="noopener"' if p[1].startswith("http") else ""
            out.append(f'<a href="{e(links.file(p[1]))}"{ext}>{e(p[2])}</a>')
        elif p[0] == "art":
            out.append(f'<a href="{e(links.art(p[1]))}">{e(p[2])}</a>')
        elif p[0] == "em":
            out.append(f"<em>{e(p[1])}</em>")
        elif p[0] == "b":
            out.append(f"<strong>{e(p[1])}</strong>")
        elif p[0] == "muted":
            out.append(f'<span class="muted">{e(p[1])}</span>' if p[1] else "")
        elif p[0] == "todo":
            out.append(f'<span class="todo">{e(p[1])}</span>')
        elif p[0] == "badge":
            out.append(f'<span class="badge">{e(p[1])}</span>')
        elif p[0] == "sub" and p[1]:
            out.append(f'<span class="sub">{e(p[1])}</span>')
    return "".join(out)


def h_blocks(blocks: list, links: Links) -> str:
    out = []
    for blk in blocks:
        kind = blk[0]
        if kind == "p":
            out.append(f"<p>{h_inl(blk[1], links)}</p>")
        elif kind == "h3":
            out.append(f"<h3>{html.escape(blk[1])}</h3>")
        elif kind == "fields":
            out.append(
                '<dl class="fields">'
                + "".join(f"<dt>{html.escape(label)}</dt><dd>{h_inl(v, links)}</dd>" for label, v in blk[1])
                + "</dl>"
            )
        elif kind == "bullets":
            out.append("<ul>" + "".join(f"<li>{h_inl(v, links)}</li>" for v in blk[1]) + "</ul>")
        elif kind == "table":
            head = "".join(f"<th>{html.escape(h)}</th>" for h in blk[1])
            rows = "".join(
                "<tr>"
                + "".join(
                    f"<td{' class=value' if blk[1][j] == 'Value' else ''}{' class=star' if blk[1][j] == '★' else ''}>"
                    f"{h_inl(c, links)}</td>"
                    for j, c in enumerate(row)
                )
                + "</tr>"
                for row in blk[2]
            )
            out.append(
                f'<div class="tablewrap"><table><thead><tr>{head}</tr></thead><tbody>{rows}</tbody></table></div>'
            )
        elif kind == "quote":
            out.append(f"<blockquote><p>“{h_inl(blk[1], links)}”</p><cite>{h_inl(blk[2], links)}</cite></blockquote>")
        elif kind == "figure":
            out.append(
                f'<figure><img src="{html.escape(links.file(blk[1]))}" alt="{html.escape(blk[2])}" loading="lazy">'
                f"<figcaption>{h_inl(blk[3], links)}</figcaption></figure>"
            )
        elif kind == "source":
            out.append(f'<p class="source">{h_inl(blk[1], links)}</p>')
    return "\n".join(out)


def html_doc(title: str, body: str) -> str:
    return (
        '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
        f"<title>{html.escape(title)}</title>\n<!-- {GENERATED} -->\n<style>\n{CSS}</style>\n</head>\n"
        f'<body>\n<div class="page">\n{body}\n</div>\n</body>\n</html>\n'
    )


def article_md(rec: dict, coll: dict) -> str:
    """The article's summary in Markdown (`export`); its file links are relative to its folder."""
    v = article_view(rec, coll)
    md_links = Links("md", coll.biblio, v["key"])

    md = [f"<!-- {GENERATED} {v['key']} -->", f"# {v['title']}", ""]
    md.append(md_mark(md_inl(v["kicker"], md_links), "**") + (" · `draft`" if v["draft"] else "") + "  ")
    md.append(f"{v['authors']}  ")
    md.append(f"{md_inl(v['meta'], md_links)}  ")
    md.append(f"Lab: {md_inl(v['lab'], md_links)}  ")
    md.append("Files: " + " · ".join(f"[{label}]({href})" for href, label, _ in v["files"]))
    md += ["", f"> {md_inl(v['lead'], md_links)}", "", "## At a glance", "", "| | |", "|---|---|"]
    md += [
        f"| **{label}** | " + "<br>".join(md_cell(line, md_links) for line in lines) + " |"
        for label, lines in v["glance"]
    ]
    for i, (_, title, blocks) in enumerate(v["sections"], 1):
        md += ["", f"## {i}. {title}", "", md_blocks(blocks, md_links)]
    md += ["", "---", "", f"*{md_inl(v['footer'], md_links)}*", ""]
    return "\n".join(md)


def note_inl(parts: list) -> str:
    """Inline parts as the HTML of a Zotero note: a web link stays a link; a link to the folder's files (attached
    beside the note) or to another article is its text, which a note cannot follow."""
    e = html.escape
    out = []
    for p in parts:
        if isinstance(p, str):
            out.append(e(p))
        elif p[0] == "a" and p[1].startswith(("http:", "https:")):
            out.append(f'<a href="{e(p[1])}">{e(p[2])}</a>')
        elif p[0] in ("a", "art"):
            out.append(e(p[2]))
        elif p[0] in ("em", "muted") and p[1]:
            out.append(f"<em>{e(p[1])}</em>")
        elif p[0] in ("b", "todo"):
            out.append(f"<strong>{e(p[1])}</strong>")
        elif p[0] == "badge":
            out.append(f" <code>{e(p[1])}</code>")
        elif p[0] == "sub" and p[1]:
            out.append(f" — {e(p[1])}")
    return re.sub(r"\s*\n\s*", " ", "".join(out))


def note_blocks(blocks: list) -> str:
    e = html.escape
    out = []
    for blk in blocks:
        kind = blk[0]
        if kind == "p":
            out.append(f"<p>{note_inl(blk[1])}</p>")
        elif kind == "h3":
            out.append(f"<h3>{e(blk[1])}</h3>")
        elif kind == "fields":
            out.append(
                "<ul>"
                + "".join(f"<li><strong>{e(label)}:</strong> {note_inl(v)}</li>" for label, v in blk[1])
                + "</ul>"
            )
        elif kind == "bullets":
            out.append("<ul>" + "".join(f"<li>{note_inl(v)}</li>" for v in blk[1]) + "</ul>")
        elif kind == "table":
            head = "".join(f"<th>{e(h)}</th>" for h in blk[1])
            rows = "".join("<tr>" + "".join(f"<td>{note_inl(c)}</td>" for c in row) + "</tr>" for row in blk[2])
            out.append(f"<table><tr>{head}</tr>{rows}</table>")
        elif kind == "quote":
            out.append(f"<blockquote><p>“{note_inl(blk[1])}”<br>— {note_inl(blk[2])}</p></blockquote>")
        elif kind == "figure":
            out.append(f"<p>[{e(blk[2])}: {e(blk[1])}] <em>{note_inl(blk[3])}</em></p>")
        elif kind == "source":
            out.append(f"<p><em>{note_inl(blk[1])}</em></p>")
    return "\n".join(out)


def article_note(rec: dict, coll: dict) -> str:
    """The article's summary, the text `export` prints, as the HTML of a Zotero note."""
    v = article_view(rec, coll)
    e = html.escape
    head = [
        f"<strong>{note_inl(v['kicker'])}</strong>" + (" <code>draft</code>" if v["draft"] else ""),
        e(v["authors"]),
    ]
    head += [
        note_inl(v["meta"]),
        f"Lab: {note_inl(v['lab'])}",
        "Files: " + " · ".join(e(lb) for _, lb, _ in v["files"]),
    ]
    glance = "".join(
        f"<tr><td><strong>{e(label)}</strong></td><td>{'<br>'.join(note_inl(line) for line in lines)}</td></tr>"
        for label, lines in v["glance"]
    )
    out = [f"<h1>{e(v['title'])}</h1>", f"<p>{'<br>'.join(head)}</p>"]
    out += [
        f"<blockquote><p>{note_inl(v['lead'])}</p></blockquote>",
        "<h2>At a glance</h2>",
        f"<table>{glance}</table>",
    ]
    for i, (_, title, blocks) in enumerate(v["sections"], 1):
        out += [f"<h2>{i}. {e(title)}</h2>", note_blocks(blocks)]
    out += ["<hr>", f"<p><em>{note_inl(v['footer'])}</em></p>"]
    return "\n".join(out)


def article_html(rec: dict, coll: dict) -> str:
    """The article's view in the page of every bibliography: `#<bibliography>/<key>`, its sections
    `#<bibliography>/<key>/<section>`."""
    v = article_view(rec, coll)
    h_links = Links("html", coll.biblio, v["key"])
    here = f"{coll.biblio.name}/{v['key']}"
    e = html.escape
    files = "".join(
        f'<a class="btn{" primary" if primary else ""}" href="{e(h_links.file(href))}">{e(label)}</a>'
        for href, label, primary in v["files"]
    )
    tiles = "".join(
        f'<div class="tile"><h2>{e(label)}</h2>'
        + "".join(f"<p>{h_inl(line, h_links)}</p>" for line in lines)
        + "</div>"
        for label, lines in v["glance"]
    )
    toc = "".join(
        f'<a href="#{e(here)}/{sid}">{i} {e(title)}</a>' for i, (sid, title, _) in enumerate(v["sections"], 1)
    )
    cards = "\n".join(
        f'<section class="card" id="{e(here)}/{sid}"><h2><span class="num">{i}</span>{e(title)}</h2>\n'
        f"{h_blocks(blocks, h_links)}\n</section>"
        for i, (sid, title, blocks) in enumerate(v["sections"], 1)
    )
    body = (
        f'<nav class="crumbs"><a href="#{e(coll.biblio.name)}">{e(coll.biblio.title)}</a> / {e(v["key"])}'
        + (' <span class="badge draft">draft</span>' if v["draft"] else "")
        + "</nav>\n"
        f'<header>\n<p class="kicker">{h_inl(v["kicker"], h_links)}</p>\n<h1>{e(v["title"])}</h1>\n'
        f'<p class="authors">{e(v["authors"])}</p>\n<p class="meta">{h_inl(v["meta"], h_links)}</p>\n'
        f'<p class="meta">Lab: {h_inl(v["lab"], h_links)}</p>\n<div class="files">{files}</div>\n'
        f'<p class="lead">{h_inl(v["lead"], h_links)}</p>\n</header>\n'
        f'<section class="glance" aria-label="At a glance">{tiles}</section>\n'
        f'<nav class="toc" aria-label="Sections">{toc}</nav>\n<main>\n{cards}\n</main>\n'
        f"<footer>{h_inl(v['footer'], h_links)}</footer>"
    )
    return f'<article class="view" id="v-{e(here)}" data-bib="{e(coll.biblio.name)}" hidden>\n{body}\n</article>'


def hub_order(recs: dict) -> list[str]:
    return sorted(recs, key=lambda k: (-int(recs[k]["bib"].get("year") or 0), k))


def hub_article(k: str, r: dict) -> list:
    return [
        ("art", k, r["bib"]["cite"]),
        ("sub", r["bib"]["title"]),
        ("sub", r["bib"]["place"] if not pending(r["bib"]["place"]) else ""),
    ]


def articles_table(coll: dict, head: list[str], row) -> tuple:
    """The table of a bibliography's articles, newest first: `row(key, rec)` gives the cells after the article's
    of a complete record; a draft says so, a record that does not render is marked unreadable."""
    recs = coll.recs
    rows = []
    for k in hub_order(recs):
        r = recs[k]
        try:
            article = hub_article(k, r)
            if r.get("status") != "complete":
                rows.append([article + [("badge", "draft")]] + [[("muted", "being curated")]] * (len(head) - 1))
                continue
            rows.append([article, *row(k, r)])
        except (KeyError, TypeError):
            rows.append([[("art", k, k), ("badge", "record unreadable")]] + [[] for _ in head[1:]])
    return ("table", head, rows)


def kind_table(coll: dict) -> tuple:
    """The kinds of the bibliography's articles: each with what it means and its articles."""
    recs = coll.recs
    order = hub_order(recs)
    rows = []
    for kind, entry in coll.biblio.vocab[coll.biblio.kind_vocab].items():
        keys = [k for k in order if recs[k].get("kind") == kind]
        if keys:
            rows.append(
                [
                    [("b", entry["label"])],
                    [entry["means"]],
                    joined([[("art", k, recs[k]["bib"]["cite"])] for k in keys]),
                ]
            )
    return ("table", ["Kind", "What it is", "Articles"], rows)


def hub_tables(coll: dict) -> list:
    """The bibliography's tables, as its profile draws them: [(id, title, ("table", head, rows))]."""
    return coll.biblio.plugin.hub_tables(coll)


def hub_html(coll: dict) -> str:
    """The bibliography's view in the page of every bibliography: `#<bibliography>`."""
    recs = coll.recs
    n, done = len(recs), sum(1 for r in recs.values() if r.get("status") == "complete")
    intro = (
        f"{n} article{'s' if n != 1 else ''} ({done} complete). One folder per article: the PDF, "
        "record.json, the figures cropped from the paper and the supplementary files."
    )
    h_links = Links("html", coll.biblio)
    e = html.escape
    cards = []
    for sid, title, table in hub_tables(coll):
        content = h_blocks([table], h_links) if table[2] else '<p class="muted">none yet</p>'
        if sid == "articles":
            content = content.replace(
                '<div class="tablewrap"><table>', '<div class="tablewrap"><table class="articles">', 1
            )
        cards.append(
            f'<section class="card hub-{sid}" id="{e(coll.biblio.name)}:{sid}"><h2>{e(title)}</h2>\n{content}\n</section>'
        )
    return (
        f'<section class="view hub" id="v-{e(coll.biblio.name)}" data-bib="{e(coll.biblio.name)}" hidden>\n'
        f'<header class="hubhead"><div><h1>{e(coll.biblio.title)}</h1><p>{e(intro)}</p></div></header>\n<main>\n'
        + "\n".join(cards)
        + "\n</main>\n</section>"
    )
